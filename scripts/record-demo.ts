// Regenerates src/lib/office/recording.ts from REAL Docker sandbox runs. Usage: npx tsx scripts/record-demo.ts (needs Docker).
import { writeFileSync } from "node:fs";
import { runNodeSuite } from "@/lib/sandbox/runner";
import { REPOS, VALIDATION_FIXTURE } from "@/lib/missions/repos";
const repo = REPOS["checkout-validation"];
const probeFile = (id: string) => {
  const p = repo.probes.find((x) => x.id === id)!;
  return `const test = require('node:test');\nconst assert = require('node:assert');\nconst m = require('./validation.js');\ntest(${JSON.stringify(`probe ${p.id}: ${p.description}`)}, () => {\n  ${p.test}\n});\n`;
};
async function run(id: string, code: string, kind: "suite" | "probes") {
  const files: Record<string, string> = { "validation.js": code };
  if (kind === "suite") files["validation.test.js"] = VALIDATION_FIXTURE.TESTS;
  else for (const p of repo.requiredProbes) files[`probe-${p}.test.js`] = probeFile(p);
  const r = await runNodeSuite(files, { timeoutMs: 60000 });
  if (r.mode !== "docker") throw new Error("sandbox not available — refusing to record");
  return { id, kind, mode: r.mode, passed: r.passed, failed: r.failed, total: r.total, cases: r.cases, durationMs: r.durationMs };
}
(async () => {
  const runs = [
    await run("reproduce", VALIDATION_FIXTURE.BUGGY, "suite"),
    await run("verify-1", VALIDATION_FIXTURE.MINIMAL, "suite"),
    await run("review-1", VALIDATION_FIXTURE.MINIMAL, "probes"),
    await run("verify-2", VALIDATION_FIXTURE.FIXED, "suite"),
    await run("review-2", VALIDATION_FIXTURE.FIXED, "probes"),
  ];
  const out = { recordedAt: new Date().toISOString(), image: process.env.AURA_SANDBOX_IMAGE || "node:20-alpine", command: "node --test", network: "none", runs };
  const ts = `/**\n * RECORDED sandbox evidence for the landing-page demo. Generated by running\n * AURA's own runner (src/lib/sandbox/runner.ts runNodeSuite → Docker, --network=none)\n * on the checkout-validation fixture (src/lib/missions/repos.ts) at each step of\n * the demo. Not live: the demo replays these captured results and says so.\n * Regenerate: see docs/demo-mode.md. Verified against the fixtures in src/lib/office/office.test.ts.\n */\nexport const DEMO_RECORDING = ${JSON.stringify(out, null, 2)} as const;\n`;
  writeFileSync("src/lib/office/recording.ts", ts);
  console.log(runs.map((r) => `${r.id} ${r.passed}/${r.total}`).join(", "));
})();
