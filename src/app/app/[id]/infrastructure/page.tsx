"use client";

import { use, useEffect } from "react";
import { Server, AlertTriangle, Loader2 } from "lucide-react";
import { useQuery, useMutation } from "@/hooks/useApi";
import { StatusDot, Skeleton, PageHeader, SimulatedNotice, ErrorState, EmptyState } from "@/components/ui/primitives";
import { useLiveEvents } from "@/hooks/useLiveEvents";
import { useApp } from "@/lib/store";
import { cn } from "@/lib/utils";

interface Node {
  id: string;
  key: string;
  label: string;
  kind: string;
  status: string;
  cpu: number;
  memory: number;
  latencyMs: number;
  errorRate: number;
  rps: number;
}

/** Thresholds used to flag a metric; shown in the column header tooltip. */
const LIMITS = { cpu: 80, memory: 85, latencyMs: 300, errorRate: 2 };

export default function InfrastructurePage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = use(params);
  const { data, loading, error, refetch } = useQuery<Node[]>(`/api/companies/${id}/infrastructure`, 4000);
  const { version } = useLiveEvents(id);
  const { mutate, loading: chaosing } = useMutation();
  const { toast } = useApp();

  useEffect(() => {
    if (version > 0) refetch();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [version]);

  async function chaos() {
    try {
      await mutate(`/api/companies/${id}/chaos`, {});
      refetch();
      toast({ title: "Chaos event injected", description: "A simulated service degradation was applied.", level: "warning" });
    } catch (e) {
      toast({ title: "Chaos event failed", description: (e as Error).message, level: "danger" });
    }
  }

  const unhealthy = data?.filter((n) => n.status !== "HEALTHY").length ?? 0;
  const totalRps = data?.reduce((s, n) => s + n.rps, 0) ?? 0;

  return (
    <div className="page">
      <PageHeader
        title="Infrastructure"
        description="Simulated services backing the product, with current resource and error metrics."
        meta={data && <span className="mono text-xs text-text-faint">{data.length - unhealthy}/{data.length} healthy · {Math.round(totalRps)} req/s</span>}
        actions={
          <button onClick={chaos} disabled={chaosing} className="btn-secondary">
            {chaosing ? <Loader2 className="h-3.5 w-3.5 animate-spin" /> : <AlertTriangle className="h-3.5 w-3.5" />}
            Inject chaos event
          </button>
        }
      />
      <div className="mb-4"><SimulatedNotice>Metrics are generated by the AURA simulation engine; they drift each simulated day and react to range exercises.</SimulatedNotice></div>

      {error && !data ? (
        <ErrorState message={error} onRetry={refetch} />
      ) : loading && !data ? (
        <div className="space-y-1">{[...Array(9)].map((_, i) => <Skeleton key={i} className="h-10" />)}</div>
      ) : !data || data.length === 0 ? (
        <EmptyState icon={Server} title="No services" description="Services are provisioned when a company is created." />
      ) : (
        <div className="overflow-x-auto rounded-lg border border-border">
          <table className="table min-w-[860px]">
            <thead className="bg-bg-raised">
              <tr>
                <th>Service</th>
                <th>Kind</th>
                <th>Status</th>
                <th title={`Flagged above ${LIMITS.cpu}%`}>CPU</th>
                <th title={`Flagged above ${LIMITS.memory}%`}>Memory</th>
                <th className="text-right" title={`Flagged above ${LIMITS.latencyMs}ms`}>Latency</th>
                <th className="text-right" title={`Flagged above ${LIMITS.errorRate}%`}>Errors</th>
                <th className="text-right">Req/s</th>
              </tr>
            </thead>
            <tbody>
              {data.map((n) => (
                <tr key={n.id}>
                  <td><div className="text-sm">{n.label}</div><div className="mono text-2xs text-text-faint">{n.key}</div></td>
                  <td className="text-xs text-text-muted">{n.kind}</td>
                  <td><StatusDot status={n.status} /></td>
                  <td><Meter value={n.cpu} hot={n.cpu > LIMITS.cpu} /></td>
                  <td><Meter value={n.memory} hot={n.memory > LIMITS.memory} /></td>
                  <td className={cn("mono text-right", n.latencyMs > LIMITS.latencyMs ? "text-danger" : "text-text-muted")}>{Math.round(n.latencyMs)}ms</td>
                  <td className={cn("mono text-right", n.errorRate > LIMITS.errorRate ? "text-danger" : "text-text-muted")}>{n.errorRate.toFixed(2)}%</td>
                  <td className="mono text-right text-text-muted">{Math.round(n.rps)}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
}

function Meter({ value, hot }: { value: number; hot: boolean }) {
  return (
    <div className="flex items-center gap-2">
      <div className="h-1 w-20 rounded-full bg-bg-elevated">
        <div className={cn("h-1 rounded-full", hot ? "bg-danger" : "bg-text-faint")} style={{ width: `${Math.min(100, value)}%` }} />
      </div>
      <span className={cn("mono w-9 text-right text-xs", hot ? "text-danger" : "text-text-muted")}>{Math.round(value)}%</span>
    </div>
  );
}
